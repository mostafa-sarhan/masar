export interface City {
  code: string;
  governorate: string;
  ar: string;
  en: string;
}
export interface Governorate {
  code: string;
  ar: string;
  en: string;
  cities: City[];
}

const slug = (en: string) =>
  en
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

export const GOVERNORATES: readonly Governorate[] = RAW.map((g) => ({
  code: g.code,
  ar: g.ar,
  en: g.en,
  cities: g.cities.map(([ar, en]) => ({ code: `${g.code}-${slug(en)}`, governorate: g.code, ar, en })),
}));

export const GOVERNORATE_CODES = GOVERNORATES.map((g) => g.code) as [string, ...string[]];

const byGovernorate = new Map(GOVERNORATES.map((g) => [g.code, g]));
const byCity = new Map(GOVERNORATES.flatMap((g) => g.cities.map((c) => [c.code, c] as const)));

export const getGovernorate = (code: string | null | undefined) => (code ? byGovernorate.get(code) : undefined);
export const getCity = (code: string | null | undefined) => (code ? byCity.get(code) : undefined);
export const isCityOf = (city: string, governorate: string) => byCity.get(city)?.governorate === governorate;

// "مدينة نصر، القاهرة" for labels and exports.
export function placeLabel(governorate?: string | null, city?: string | null, lang: "ar" | "en" = "ar") {
  const g = getGovernorate(governorate);
  const c = getCity(city);
  return [c?.[lang], g?.[lang]].filter(Boolean).join(lang === "ar" ? "، " : ", ");
}
